// Regenerate Formula/<name>.rb for each entry in packages.json from that
// project's latest GitHub release.
//
// Usage: bun scripts/update-formulae.ts [name...]
// Env:   GITHUB_TOKEN (optional; raises the API rate limit)
//
// A release must contain one archive per platform named
// <name>-<version>-<os>-<arch>.tar.gz (os: darwin|linux, arch: arm64|x64)
// and a checksums.txt in `sha256sum` format covering them.
import path from "node:path";

export interface Package {
  name: string;
  repo: string;
  desc: string;
  license: string;
  homepage?: string;
  dependencies?: string[];
  /** Executables to install from the archive; defaults to [name]. */
  binaries?: string[];
}

export interface Archive {
  os: "darwin" | "linux";
  arch: "arm64" | "x64";
  url: string;
  sha256: string;
}

const PLATFORMS = [
  { os: "darwin", arch: "arm64" },
  { os: "darwin", arch: "x64" },
  { os: "linux", arch: "arm64" },
  { os: "linux", arch: "x64" },
] as const;

/** Homebrew's formula class name: "foo-bar" -> "FooBar", "foo@2" -> "FooAT2". */
export function className(name: string): string {
  return name
    .replace(/@/g, "AT")
    .split(/[-_.]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const quote = (s: string) => JSON.stringify(s);

export function renderFormula(pkg: Package, archives: Archive[]): string {
  const block = (os: Archive["os"]) => {
    const forOs = archives.filter((a) => a.os === os);
    if (forOs.length === 0) return [];
    const lines = [`  on_${os === "darwin" ? "macos" : "linux"} do`];
    for (const a of forOs) {
      lines.push(
        `    on_${a.arch === "arm64" ? "arm" : "intel"} do`,
        `      url ${quote(a.url)}`,
        `      sha256 ${quote(a.sha256)}`,
        "    end",
      );
      if (a !== forOs.at(-1)) lines.push("");
    }
    lines.push("  end");
    return lines;
  };
  const binaries = pkg.binaries ?? [pkg.name];
  const deps = (pkg.dependencies ?? []).map((d) => `  depends_on ${quote(d)}`);
  const macos = block("darwin");
  const linux = block("linux");
  return [
    "# Generated by scripts/update-formulae.ts from the latest GitHub release. Do not edit.",
    `class ${className(pkg.name)} < Formula`,
    `  desc ${quote(pkg.desc)}`,
    `  homepage ${quote(pkg.homepage ?? `https://github.com/${pkg.repo}`)}`,
    `  license ${quote(pkg.license)}`,
    ...(deps.length ? ["", ...deps] : []),
    ...(macos.length ? ["", ...macos] : []),
    ...(linux.length ? ["", ...linux] : []),
    "",
    "  def install",
    `    bin.install ${binaries.map(quote).join(", ")}`,
    "  end",
    "",
    "  test do",
    `    assert_match version.to_s, shell_output("#{bin}/${binaries[0]} --version")`,
    "  end",
    "end",
    "",
  ].join("\n");
}

export function parseChecksums(text: string): Map<string, string> {
  const sums = new Map<string, string>();
  for (const line of text.split("\n")) {
    const m = /^([0-9a-f]{64})\s+\*?(\S+)$/.exec(line.trim());
    if (m) sums.set(m[2]!, m[1]!);
  }
  return sums;
}

async function github<T>(url: string): Promise<T> {
  const res = await fetch(url.startsWith("http") ? url : `https://api.github.com${url}`, {
    headers: {
      accept: "application/vnd.github+json",
      ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
    },
  });
  if (!res.ok) throw new Error(`${url}: ${res.status} ${res.statusText}`);
  return (await res.json()) as T;
}

interface Release {
  tag_name: string;
  assets: { name: string; browser_download_url: string }[];
}

export async function archivesFor(pkg: Package): Promise<{ version: string; archives: Archive[] }> {
  const release = await github<Release>(`/repos/${pkg.repo}/releases/latest`);
  const version = release.tag_name.replace(/^v/, "");
  const checksums = release.assets.find((a) => a.name === "checksums.txt");
  if (!checksums) throw new Error(`${pkg.repo} ${release.tag_name}: no checksums.txt asset`);
  const res = await fetch(checksums.browser_download_url);
  if (!res.ok) throw new Error(`checksums.txt: ${res.status}`);
  const sums = parseChecksums(await res.text());
  const archives: Archive[] = [];
  for (const { os, arch } of PLATFORMS) {
    const file = `${pkg.name}-${version}-${os}-${arch}.tar.gz`;
    const asset = release.assets.find((a) => a.name === file);
    const sha256 = sums.get(file);
    if (asset && sha256) archives.push({ os, arch, url: asset.browser_download_url, sha256 });
    else if (asset || sha256) throw new Error(`${file}: archive and checksum must both be present`);
  }
  if (archives.length === 0) throw new Error(`${pkg.repo} ${release.tag_name}: no archives named ${pkg.name}-${version}-<os>-<arch>.tar.gz`);
  return { version, archives };
}

if (import.meta.main) {
  const root = path.join(import.meta.dir, "..");
  const { packages } = (await Bun.file(path.join(root, "packages.json")).json()) as { packages: Package[] };
  const only = process.argv.slice(2).filter(Boolean);
  const unknown = only.filter((n) => !packages.some((p) => p.name === n));
  if (unknown.length) throw new Error(`unknown package(s): ${unknown.join(", ")}`);
  let failed = false;
  for (const pkg of packages.filter((p) => only.length === 0 || only.includes(p.name))) {
    try {
      const { version, archives } = await archivesFor(pkg);
      const file = path.join(root, "Formula", `${pkg.name}.rb`);
      const next = renderFormula(pkg, archives);
      const current = (await Bun.file(file).exists()) ? await Bun.file(file).text() : "";
      if (current === next) {
        console.log(`${pkg.name}: up to date (${version})`);
      } else {
        await Bun.write(file, next);
        console.log(`${pkg.name}: updated to ${version} (${archives.map((a) => `${a.os}-${a.arch}`).join(", ")})`);
      }
    } catch (e) {
      failed = true;
      console.error(`${pkg.name}: ${(e as Error).message}`);
    }
  }
  if (failed) process.exit(1);
}
